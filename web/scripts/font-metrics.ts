import type { StandardFont } from "../placement";

export interface FontMetrics {
  /** Units per 1000 of the font size. */
  ascender: number;
  /** Negative: below the baseline. */
  descender: number;
  /** Advance width of each WinAnsiEncoding byte (0 where none). */
  widths: number[];
}

