if (WIN_ANSI.length !== 0x100 - 0x20) throw new Error(`WIN_ANSI has ${WIN_ANSI.length} names`);

interface Afm {
  ascender: number;
  descender: number;
  widths: Map<string, number>;
}

function parseAfm(text: string): Afm {
  const header = (key: string) => {
    const line = text.split("\n").find((l) => l.startsWith(`${key} `));
    if (!line) throw new Error(`missing ${key}`);
    return Number(line.slice(key.length + 1));
  };
  const widths = new Map<string, number>();
  // "C 65 ; WX 667 ; N A ; B 14 0 654 718 ;"
  for (const match of text.matchAll(/^C -?\d+ ; WX (\d+) ; N (\S+) ;/gm)) widths.set(match[2], Number(match[1]));
  return { ascender: header("Ascender"), descender: header("Descender"), widths };
}

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun scripts/font-metrics.ts <afm dir>");

const entries = FONTS.map((font) => {
  const afm = parseAfm(readFileSync(join(dir, `${font}.afm`), "utf8"));
  const widths = Array.from({ length: 256 }, (_, byte) => {
    const name = byte >= 0x20 ? WIN_ANSI[byte - 0x20] : "-";
    if (name === "-") return 0;
    const width = afm.widths.get(name);
    if (width === undefined) throw new Error(`${font} has no ${name}`);
    return width;
  });
  return `  "${font}": {\n    ascender: ${afm.ascender},\n    descender: ${afm.descender},\n    widths: [${widths.join(", ")}],\n  },`;
});

