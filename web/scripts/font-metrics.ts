// Generates src/text/metrics.ts: the advance widths of the 12 standard PDF text
// fonts over WinAnsiEncoding, plus ascender and descender, from Adobe's Core 14
// AFM files. The output is committed; rerun only if the table format changes.
//
// Usage: bun scripts/font-metrics.ts <dir with Helvetica.afm, Times-Roman.afm, …>
//
// The AFM files ship in the `pdfkit` npm package (js/data/), among others.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FONTS = [
  "Helvetica",
  "Helvetica-Bold",
  "Helvetica-Oblique",
  "Helvetica-BoldOblique",
  "Times-Roman",
  "Times-Bold",
  "Times-Italic",
  "Times-BoldItalic",
  "Courier",
  "Courier-Bold",
  "Courier-Oblique",
  "Courier-BoldOblique",
];

